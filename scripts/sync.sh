#!/usr/bin/env bash
set -e
# Idempotent: brings certificates, DNS and Traefik in line with DEV_DOMAIN.
source "$(dirname "${BASH_SOURCE[0]}")/env.sh"

CRT="$ROOT_DIR/shared/certs/local.crt"
KEY="$ROOT_DIR/shared/certs/local.key"
THIRTY_DAYS=2592000

# --------------------------------------------------
# DNS is needed only on a Linux server inside a tailnet
# --------------------------------------------------
DEV_DNS_IP=""
if [ "$DEV_DOMAIN" != "$DEFAULT_DOMAIN" ] && [ "$(uname -s)" = "Linux" ] && command -v tailscale >/dev/null 2>&1; then
  DEV_DNS_IP="$(tailscale ip -4 2>/dev/null | head -n 1 || true)"
fi
COMPOSE_PROFILES=""
[ -n "$DEV_DNS_IP" ] && COMPOSE_PROFILES="dns"

cat > "$ROOT_DIR/traefik/.env" <<EOF
# Generated by scripts/sync.sh, do not edit. Change the domain with: make domain name=...
DEV_DOMAIN=${DEV_DOMAIN}
TRAEFIK_HOST=${TRAEFIK_HOST}
WHOAMI_HOST=${WHOAMI_HOST}
DEV_DNS_IP=${DEV_DNS_IP}
COMPOSE_PROFILES=${COMPOSE_PROFILES}
EOF

# --------------------------------------------------
# Certificate
# --------------------------------------------------
cert_is_valid() {
  [ -f "$CRT" ] && [ -f "$KEY" ] \
    && openssl x509 -in "$CRT" -noout -checkend "$THIRTY_DAYS" >/dev/null 2>&1 \
    && openssl x509 -in "$CRT" -noout -text | grep -qF "DNS:*.${DEV_DOMAIN}"
}

CERT_CHANGED=""
if ! cert_is_valid; then
  echo "🔐 Certificate does not cover ${DEV_DOMAIN} or is expiring, regenerating"
  "$ROOT_DIR/scripts/generate-certs.sh"
  CERT_CHANGED="1"
fi

# --------------------------------------------------
# Traefik and DNS
# --------------------------------------------------
cd "$ROOT_DIR/traefik"
docker compose up -d

[ -z "$COMPOSE_PROFILES" ] && docker rm -f dev-dns >/dev/null 2>&1 || true
[ -n "$CERT_CHANGED" ] && docker restart traefik >/dev/null

echo "✅ Domain: *.${DEV_DOMAIN}"
